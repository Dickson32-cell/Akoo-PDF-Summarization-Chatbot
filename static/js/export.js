// Export namespace - Created by Abdul Rashid Dickson
const AkooExport = {
    // Creator attribution
    CREATOR: 'Abdul Rashid Dickson',
    COPYRIGHT: '© 2025 Abdul Rashid Dickson. All Rights Reserved.',
    PROJECT: 'AKOO AI - Advanced PDF Intelligence Platform',

    /**
     * Generate document header with attribution
     */
    getHeader(format = 'markdown') {
        const header = `
╔══════════════════════════════════════════════════════════════════════════════╗
║     AKOO AI - Advanced PDF Intelligence Platform                            ║
║     Created by: Abdul Rashid Dickson                                        ║
║     © 2025 All Rights Reserved                                              ║
╚══════════════════════════════════════════════════════════════════════════════╝
`;

        if (format === 'markdown') {
            return `\`\`\`\n${header}\n\`\`\`\n\n`;
        } else if (format === 'html') {
            return `<pre>${header}</pre>`;
        }
        return header;
    },

    /**
     * Get footer with timestamp and attribution
     */
    getFooter() {
        const now = new Date().toLocaleString();
        return `\n\n---\nGenerated by AKOO AI on ${now}\nCreated by: Abdul Rashid Dickson\n© 2025 All Rights Reserved\n`;
    },

    /**
     * Export summary as Markdown
     */
    exportAsMarkdown(title, summary, metadata = {}) {
        let markdown = this.getHeader('markdown');
        markdown += `# ${title}\n\n`;
        markdown += `**Generated:** ${new Date().toLocaleString()}\n`;
        markdown += `**Platform:** AKOO AI - Created by Abdul Rashid Dickson\n\n`;

        if (metadata.documentName) {
            markdown += `**Source Document:** ${metadata.documentName}\n`;
        }
        if (metadata.pageCount) {
            markdown += `**Pages:** ${metadata.pageCount}\n`;
        }
        markdown += `\n---\n\n`;
        markdown += `## Summary\n\n${summary}`;
        markdown += this.getFooter();

        return markdown;
    },

    /**
     * Export summary as JSON
     */
    exportAsJSON(title, summary, metadata = {}) {
        const exportData = {
            _attribution: {
                creator: this.CREATOR,
                copyright: this.COPYRIGHT,
                project: this.PROJECT,
                generatedAt: new Date().toISOString(),
                signature: 'AKOO-ARD-2025'
            },
            document: {
                title: title,
                ...metadata
            },
            summary: summary,
            exportedAt: new Date().toISOString()
        };

        return JSON.stringify(exportData, null, 2);
    },

    /**
     * Export summary as plain text
     */
    exportAsText(title, summary, metadata = {}) {
        let text = this.getHeader('text');
        text += `\n${title}\n${'='.repeat(title.length)}\n\n`;
        text += `Generated: ${new Date().toLocaleString()}\n`;
        text += `Platform: AKOO AI - Created by Abdul Rashid Dickson\n\n`;

        if (metadata.documentName) {
            text += `Source: ${metadata.documentName}\n`;
        }
        text += `\n${'-'.repeat(50)}\n\n`;
        text += summary;
        text += this.getFooter();

        return text;
    },

    /**
     * Generate HTML for PDF export
     */
    exportAsHTML(title, summary, metadata = {}) {
        return `
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="author" content="Abdul Rashid Dickson">
    <meta name="generator" content="AKOO AI">
    <title>${title}</title>
    <style>
        body {
            font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif;
            max-width: 800px;
            margin: 40px auto;
            padding: 20px;
            line-height: 1.6;
            color: #333;
        }
        .header {
            text-align: center;
            border-bottom: 2px solid #667eea;
            padding-bottom: 20px;
            margin-bottom: 30px;
        }
        .logo { color: #667eea; font-size: 24px; font-weight: bold; }
        .meta { color: #666; font-size: 14px; margin-top: 10px; }
        h1 { color: #1a1a2e; }
        .summary { 
            background: #f8f9fa; 
            padding: 20px; 
            border-radius: 8px; 
            border-left: 4px solid #667eea;
        }
        .footer {
            margin-top: 40px;
            padding-top: 20px;
            border-top: 1px solid #ddd;
            text-align: center;
            color: #666;
            font-size: 12px;
        }
        .creator {
            background: linear-gradient(135deg, #667eea, #764ba2);
            -webkit-background-clip: text;
            -webkit-text-fill-color: transparent;
            font-weight: bold;
        }
    </style>
</head>
<body>
    <div class="header">
        <div class="logo">🚀 AKOO AI</div>
        <div class="meta">Advanced PDF Intelligence Platform</div>
        <div class="meta">Created by <span class="creator">Abdul Rashid Dickson</span></div>
    </div>
    
    <h1>${title}</h1>
    
    <div class="meta">
        <strong>Generated:</strong> ${new Date().toLocaleString()}<br>
        ${metadata.documentName ? `<strong>Source:</strong> ${metadata.documentName}<br>` : ''}
        ${metadata.pageCount ? `<strong>Pages:</strong> ${metadata.pageCount}<br>` : ''}
    </div>
    
    <h2>Summary</h2>
    <div class="summary">
        ${summary.replace(/\n/g, '<br>')}
    </div>
    
    <div class="footer">
        <p>Generated by AKOO AI</p>
        <p><strong>Created by: Abdul Rashid Dickson</strong></p>
        <p>© 2025 All Rights Reserved</p>
    </div>
</body>
</html>`;
    },

    /**
     * Trigger file download
     */
    downloadFile(content, filename, mimeType) {
        const blob = new Blob([content], { type: mimeType });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = filename;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);

        // Log export
        console.log(`%c AKOO AI Export `, 'background: #667eea; color: white; padding: 4px 8px; border-radius: 4px;');
        console.log(`%c Exported by: Abdul Rashid Dickson `, 'color: #667eea;');
        console.log(`File: ${filename}`);
    },

    /**
     * Export summary with format selection
     */
    exportSummary(format, title, summary, metadata = {}) {
        const timestamp = new Date().toISOString().slice(0, 10);
        const safeTitle = title.replace(/[^a-z0-9]/gi, '_').toLowerCase();

        switch (format) {
            case 'markdown':
            case 'md':
                const md = this.exportAsMarkdown(title, summary, metadata);
                this.downloadFile(md, `${safeTitle}_${timestamp}.md`, 'text/markdown');
                break;

            case 'json':
                const json = this.exportAsJSON(title, summary, metadata);
                this.downloadFile(json, `${safeTitle}_${timestamp}.json`, 'application/json');
                break;

            case 'text':
            case 'txt':
                const txt = this.exportAsText(title, summary, metadata);
                this.downloadFile(txt, `${safeTitle}_${timestamp}.txt`, 'text/plain');
                break;

            case 'html':
            case 'pdf':
                const html = this.exportAsHTML(title, summary, metadata);
                if (format === 'pdf') {
                    // Open in new window for printing as PDF
                    const printWindow = window.open('', '_blank');
                    printWindow.document.write(html);
                    printWindow.document.close();
                    printWindow.print();
                } else {
                    this.downloadFile(html, `${safeTitle}_${timestamp}.html`, 'text/html');
                }
                break;

            default:
                console.error('Unknown export format:', format);
        }
    }
};

// Make available globally
window.AkooExport = AkooExport;

